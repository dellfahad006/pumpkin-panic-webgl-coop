#!/usr/bin/env python3
"""Patch the Pumpkin Panic PUN installer/workflow so PhotonServerSettings is
created by the Unity Editor during CI. This avoids requiring a local Unity install
or a pre-generated PhotonServerSettings.asset in the private PUN package.

Run from the repository root:
    python3 /path/to/prepare_photon_settings_fix.py
"""
from pathlib import Path
import re
import sys

ROOT = Path.cwd()
installer = ROOT / 'ci/install_pun_coop.py'
workflow = ROOT / '.github/workflows/webgl.yml'
if not installer.is_file() or not workflow.is_file():
    sys.exit('Run this script from the repository root (missing ci/install_pun_coop.py or .github/workflows/webgl.yml).')

src = installer.read_text(encoding='utf-8')
# Replace the current function regardless of its exact implementation, preserving
# the rest of the installer. The CI editor step below creates the asset after PUN
# has been imported and before the actual WebGL build.
pattern = re.compile(r'(?ms)^def configure_photon_app_id\(.*?(?=^def |^class |\Z)')
m = pattern.search(src)
if not m:
    sys.exit('Could not find configure_photon_app_id() in ci/install_pun_coop.py; no files changed.')
replacement = '''def configure_photon_app_id(project_root):
    """Validate the App ID; Unity creates PhotonServerSettings after PUN import."""
    app_id = os.environ.get("PHOTON_APP_ID", "").strip()
    if not app_id:
        raise RuntimeError("PHOTON_APP_ID secret is required")
    settings = Path(project_root) / "Assets/Photon/PhotonUnityNetworking/Resources/PhotonServerSettings.asset"
    if settings.is_file():
        # If a settings asset was supplied in the SDK bundle, update it in place.
        text = settings.read_text(encoding="utf-8", errors="replace")
        if "AppIdRealtime:" in text:
            text = re.sub(r"(?m)^(\\s*AppIdRealtime:\\s*).*?$", lambda x: x.group(1) + app_id, text, count=1)
            settings.write_text(text, encoding="utf-8")
        else:
            print("PhotonServerSettings.asset exists; AppIdRealtime will be set by the Unity Editor CI step")
    else:
        print("PhotonServerSettings.asset will be generated by the Unity Editor CI step")


'''
src = src[:m.start()] + replacement + src[m.end():]
# The installer receives the project directory as its first CLI argument.
# Ensure its call uses that project path; the existing main() has a project variable.
src = re.sub(r'configure_photon_app_id\(project\)', 'configure_photon_app_id(project)', src)

# Add an Editor utility into the project. It uses PUN's own ScriptableObject type,
# so the asset serialization is produced by the matching PUN version, not guessed YAML.
editor_dir = ROOT / 'ci/pun-coop/Assets/Editor'
editor_dir.mkdir(parents=True, exist_ok=True)
editor_script = editor_dir / 'GeneratePhotonServerSettings.cs'
editor_script.write_text(r'''using System;
using System.IO;
using Photon.Realtime;
using UnityEditor;
using UnityEngine;

namespace PumpkinPanicCoop.Editor
{
    public static class GeneratePhotonServerSettings
    {
        public static void CreateOrUpdate()
        {
            string appId = Environment.GetEnvironmentVariable("PHOTON_APP_ID");
            if (string.IsNullOrEmpty(appId))
                throw new Exception("PHOTON_APP_ID environment variable is missing.");

            const string photonFolder = "Assets/Photon";
            const string punFolder = photonFolder + "/PhotonUnityNetworking";
            const string folder = punFolder + "/Resources";
            const string assetPath = folder + "/PhotonServerSettings.asset";
            if (!AssetDatabase.IsValidFolder(photonFolder))
                AssetDatabase.CreateFolder("Assets", "Photon");
            if (!AssetDatabase.IsValidFolder(punFolder))
                AssetDatabase.CreateFolder(photonFolder, "PhotonUnityNetworking");
            if (!AssetDatabase.IsValidFolder(folder))
                AssetDatabase.CreateFolder(punFolder, "Resources");

            ServerSettings settings = AssetDatabase.LoadAssetAtPath<ServerSettings>(assetPath);
            if (settings == null)
            {
                settings = ScriptableObject.CreateInstance<ServerSettings>();
                AssetDatabase.CreateAsset(settings, assetPath);
            }

            if (settings.AppSettings == null)
                settings.AppSettings = new AppSettings();
            settings.AppSettings.AppIdRealtime = appId.Trim();
            settings.AppSettings.UseNameServer = true;
            EditorUtility.SetDirty(settings);
            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh();
            Debug.Log("[PumpkinPanicCoop] PhotonServerSettings created/configured for PUN WebGL build.");
        }
    }
}
''', encoding='utf-8')

# Make sure the new Editor source is copied by install_port's existing recursive
# copy of ci/pun-coop/Assets/Scripts only if it copies all Assets. Add a direct copy
# into the project after the port install in the installer main flow.
if 'GeneratePhotonServerSettings.cs' not in src:
    # Copy the editor helper from the port bundle into the actual Unity project
    # immediately after install_port(project) inside main().
    call = re.search(r'(?m)^(\s*)install_port\(project\)\s*$', src)
    if not call:
        sys.exit('Could not locate install_port(project) in installer; no files changed.')
    indent = call.group(1)
    copy_block = (
        f"{indent}editor_source = Path(__file__).parent / \"ci/pun-coop/Assets/Editor/GeneratePhotonServerSettings.cs\"\n"
        f"{indent}editor_target = project / \"Assets/Editor/GeneratePhotonServerSettings.cs\"\n"
        f"{indent}editor_target.parent.mkdir(parents=True, exist_ok=True)\n"
        f"{indent}shutil.copy2(editor_source, editor_target)\n"
    )
    pos = call.end()
    src = src[:pos] + "\n" + copy_block.rstrip("\n") + src[pos:]

wf = workflow.read_text(encoding='utf-8')
step_name = 'Generate PhotonServerSettings with Unity Editor'
if step_name not in wf:
    anchor = '      - name: Build WebGL Project\n'
    if anchor not in wf:
        sys.exit('Could not find Build WebGL Project step in workflow; installer was not written.')
    step = '''      - name: Generate PhotonServerSettings with Unity Editor
        env:
          PHOTON_APP_ID: ${{ secrets.PHOTON_APP_ID }}
        run: |
          /home/runner/Unity/Hub/Editor/2020.3.40f1/Editor/Unity \\
            -projectPath project \\
            -logFile "$GITHUB_WORKSPACE/photon-settings.log" \\
            -batchmode -quit \\
            -executeMethod PumpkinPanicCoop.Editor.GeneratePhotonServerSettings.CreateOrUpdate
          test -f "project/Assets/Photon/PhotonUnityNetworking/Resources/PhotonServerSettings.asset"

'''
    wf = wf.replace(anchor, step + anchor, 1)

# Only write once all transformations have succeeded.
installer.write_text(src, encoding='utf-8')
workflow.write_text(wf, encoding='utf-8')
print('Applied Photon settings CI fix:')
print(' - Installer no longer requires a pre-generated PhotonServerSettings.asset')
print(' - Unity generates the asset from PUN 2.50 types during CI')
print(' - PHOTON_APP_ID remains a GitHub Actions secret')
print(' - Added ci/pun-coop/Assets/Editor/GeneratePhotonServerSettings.cs')
print('Review the diff before committing. No Git operations were performed.')
